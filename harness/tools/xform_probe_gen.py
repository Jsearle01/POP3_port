#!/usr/bin/env python3
r"""xform_probe_gen.py — P5.20: the probe's tables, its cases, and the GENERATED reference.

There is no shipped oracle for a runtime shift or mirror over gameplay cels, so the reference
is produced by the tools the bake itself uses, through the same files:

  facing 0, phase k : sprite_convert (start_col S)                      -> cel_blit_prep --phase k
  facing 1, phase k : sprite_convert (start_col S, --mirror, and --flip-parity iff 7*apple_w
                      is EVEN -- bake_scene.py:626-631's per-cel rule)  -> cel_blit_prep --phase k

and drawn by cel_blit_prep.simulate (the independent 6809-semantics replay) over the probe's
background. The probe draws ONLY the facing-0 phase-0 stream, transformed at run time, and
the checker compares the two framebuffers byte for byte.

REGISTRATION. A mirrored frame reverses all 4w of its pixels; sprite_convert's --mirror
reverses only the 7*apple_w it converted. The difference is the frame's pad,
d = 4*w0 - 7*apple_w (w0 = the stored width after trailing trim, so d can be negative), and
the runtime draw sits d pixels LEFT of the reference to put the same pixel in the same place.
That is placement arithmetic, the caller's, exactly as the phase is.

Each case is a 10-byte record: fn, stream, dest, A, B, dump length. Case 0 is always the
calibration case (fn = xp_null): the bracket's own cost, subtracted from every other.

--baked (P5.27): the probe draws the COMMITTED bake (content/chars/<tab>/<tab>_<nnn>_p0.s, with
apple_w read from content/chars/char_cels.s) in place of the stream generated here. Nothing
else moves -- the reference, the columns and the flags are computed exactly as before -- so
the run asks P5.20's question of the shipping artifact. bake_chars_check.py confirms the case
records are unchanged and compares every verdict and cycle count with P5.20's own logs.
"""
